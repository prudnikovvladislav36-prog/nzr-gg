window.NZR_CONTENT.getPublished = function () {
  return this.articles
    .filter(a => a.published !== false)
    .sort((a,b) => String(b.date).localeCompare(String(a.date)));
};
window.NZR_CONTENT.getByCategory = function (category) {
  return this.getPublished().filter(a => a.category === category);
};
window.NZR_CONTENT.getBySlug = function (slug) {
  return this.getPublished().find(a => a.slug === slug);
};
